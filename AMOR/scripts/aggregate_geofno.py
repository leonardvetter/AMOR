#!/usr/bin/env python3
"""Aggregate per-seed results into the numbers for Table tab:irregular and a setup snippet.

Writes into --out-dir (default experiments_out/geofno):
    geofno_summary.csv   mean / std (ddof=1) over seeds of rel L1 / L2 per dataset, plus model sizes
    tab_irregular.tex    the full table body (AMOR row from the result files, other rows quoted from the papers)
    setup_snippet.tex    short description of the exact setup

Usage: python AMOR/scripts/aggregate_geofno.py [--out-dir DIR]
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_OUT = REPO_ROOT / "experiments_out" / "geofno"

# Published numbers (quoted, not re-run): (airfoil, elasticity), error type
QUOTED = [
    ("Geo-FNO~\\cite{li2023fourier}", ("1.38", "L^2"), ("2.29", "L^2")),
    ("FNO interpolation~\\cite{li2023fourier}", ("4.21", "L^2"), ("5.08", "L^2")),
    ("GraphNO~\\cite{li2023fourier}", None, ("12.60", "L^2")),
    ("DeepONet~\\cite{li2023fourier}", None, ("9.65", "L^2")),
    ("DSE~\\cite{lingsch2024beyond}", ("0.220", "L^1"), ("1.73", "L^1")),
]
BEST_QUOTED = {("airfoil", "L^2"): 1.38, ("elasticity", "L^2"): 2.29,
               ("airfoil", "L^1"): 0.220, ("elasticity", "L^1"): 1.73}


def load(out: Path):
    rows = {}
    for f in sorted((out / "results").glob("*_seed*.json")):
        r = json.loads(f.read_text())
        rows.setdefault(r["dataset"], []).append(r)
    return rows


def ms(v):
    v = np.asarray(v, dtype=float)
    return float(v.mean()), float(v.std(ddof=1)) if len(v) > 1 else 0.0


def fmt(mean, std, n, digits, bold):
    s = f"{mean:.{digits}f} \\pm {std:.{digits}f}" if n > 1 else f"{mean:.{digits}f}"
    return f"\\textbf{{{s}}}" if bold else s


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out-dir", type=Path, default=DEFAULT_OUT)
    a = ap.parse_args()
    out = a.out_dir
    runs = load(out)
    if not runs:
        sys.exit(f"no results in {out / 'results'}")

    stats, summary = {}, []
    for ds, rs in runs.items():
        n = len(rs)
        l1, l2 = ms([r["rel_l1"] for r in rs]), ms([r["rel_l2"] for r in rs])
        stats[ds] = {"L^1": l1, "L^2": l2, "n": n}
        summary.append(dict(dataset=ds, n_seeds=n, seeds=sorted(r["seed"] for r in rs),
                            rel_l1_mean=l1[0], rel_l1_std=l1[1], rel_l2_mean=l2[0], rel_l2_std=l2[1],
                            k_in=sorted({r["model"]["k_in"] for r in rs}), k_out=sorted({r["model"]["k_out"] for r in rs}),
                            width=sorted({r["model"]["width"] for r in rs}), layers=rs[0]["model"]["layers"],
                            params=rs[0]["model"]["num_params"], epochs=rs[0]["config"]["epochs"],
                            train_time_s_mean=float(np.mean([r["training"]["train_time_s"] for r in rs]))))
    pd.DataFrame(summary).to_csv(out / "geofno_summary.csv", index=False)

    def amor_cell(ds):
        if ds not in stats:
            return "---"
        s, n = stats[ds], stats[ds]["n"]
        d = 3 if ds == "airfoil" else 2
        parts = []
        for typ in ("L^1", "L^2"):
            m, sd = s[typ]
            parts.append(f"${fmt(m, sd, n, d, m < BEST_QUOTED[(ds, typ)])}$ (${typ}$)")
        return " / ".join(parts)

    L = [r"\begin{tabular}{lcc}", r"\toprule", r"\textbf{Method} & \textbf{Airfoil} & \textbf{Elasticity} \\", r"\midrule", r"\midrule",
         f"AMOR & {amor_cell('airfoil')} & {amor_cell('elasticity')} \\\\", r"\midrule"]
    for name, air, ela in QUOTED:
        cell = lambda x: "---" if x is None else f"{x[0]} (${x[1]}$)"  # noqa: E731
        L.append(f"{name} & {cell(air)} & {cell(ela)} \\\\")
    L += [r"\bottomrule", r"\end{tabular}"]
    n_all = sorted({s['n'] for s in stats.values()})
    epochs = sorted({s["epochs"] for s in summary})
    if len(epochs) != 1:
        sys.exit(f"results mix different epoch counts {epochs}; aggregate only runs with the same protocol")
    head = (f"% Auto-generated by AMOR/scripts/aggregate_geofno.py. AMOR: mean $\\pm$ std (ddof=1) over {'/'.join(map(str, n_all))} seed(s) of the per-sample\n"
            "% relative error [%] on the 200 published test samples; other rows are quoted from the cited papers.\n")
    (out / "tab_irregular.tex").write_text(head + "\n".join(L) + "\n")

    k = {ds: (summary_row := [s for s in summary if s["dataset"] == ds][0]) for ds in stats}
    ks = lambda ds, key: "/".join(map(str, k[ds][key])) if ds in k else "--"  # noqa: E731
    snippet = rf"""% Auto-generated by AMOR/scripts/aggregate_geofno.py; do not edit by hand.
\paragraph{{Airfoil and Elasticity setup.}}
Both problems use the published train/test splits of Geo-FNO (1000/200 samples; no validation split). The two input
channels are the node coordinates and the output is the Mach number (airfoil, $221\times51$ C-mesh) or the stress
(elasticity, 972 nodes). The coordinates are Z-scored per node and channel over the training samples (as in Geo-FNO's
normalizer; the std is floored at $1\%$ of the channel's median node std), the output channel-wise; statistics and reduced bases are fit on the training split only.
The bases are mass-weighted PCA bases for the lumped node mass of the mean training mesh (dual-cell areas of the
C-mesh quads, resp.\ Delaunay-triangle areas of the point cloud), with $(k_{{\mathrm{{in}}}},k_{{\mathrm{{out}}}})$ chosen to explain
$99.9\%$ of the variance ({ks('airfoil','k_in')}/{ks('airfoil','k_out')} airfoil, {ks('elasticity','k_in')}/{ks('elasticity','k_out')} elasticity, over seeds).
AMOR uses factorized weights, width $\lfloor k_{{\mathrm{{out}}}}/2\rfloor$ and 6 (airfoil) resp.\ 4 (elasticity) blocks.
Training uses AdamW (learning rate $2\cdot10^{{-3}}$, weight decay $10^{{-4}}$), cosine annealing, batch size 20, gradient clipping
at $3$, and the relative $L^2$ loss of the physical fields for {epochs[0]} epochs; the model after the last epoch is evaluated
(no early stopping). Errors are mean per-sample relative $L^1$/$L^2$ errors of the physical fields on the 200 test samples
(mean $\pm$ std over {'/'.join(map(str, n_all))} seeds; seeds vary initialisation and batch order).
"""
    (out / "setup_snippet.tex").write_text(snippet)
    print(pd.DataFrame(summary).drop(columns=["seeds"]).to_string(index=False))
    print(f"\nwrote {out / 'geofno_summary.csv'}, tab_irregular.tex, setup_snippet.tex")


if __name__ == "__main__":
    main()
